  make(2, '材料労務', ITEMS.map((_, i) => i + 1)); // 基準点 160
  make(3, '労務', [1, 2, 3, 5, 6, 7, 8, 10, 11, 12, 13, 14, 15, 17, 18, 19, 20, 21, 22]); // 基準点 145
